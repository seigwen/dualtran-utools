#!/usr/bin/env node
/**
 * build-i18n.mjs — bundle every `locales/<code>/messages.json` plus the runtime
 * into a single `dist/i18n.js`.
 *
 * One file because the page is loaded from an asar bundle, where fetching local
 * JSON at runtime is not dependable.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = path.join(ROOT, "locales");
const RUNTIME = path.join(ROOT, "src", "i18n.js");
const OUT = path.join(ROOT, "dist", "i18n.js");

const locales = {};
for (const entry of fs.readdirSync(LOCALES, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = path.join(LOCALES, entry.name, "messages.json");
  if (!fs.existsSync(file)) continue;
  locales[entry.name] = JSON.parse(fs.readFileSync(file, "utf8"));
}

const runtime = fs.readFileSync(RUNTIME, "utf8");
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  [
    "/* Generated by scripts/build-i18n.mjs — do not edit. */",
    "window.DT_LOCALES = " + JSON.stringify(locales) + ";",
    runtime,
    "",
  ].join("\n")
);
const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(`[build-i18n] ${Object.keys(locales).length} locales → dist/i18n.js (${kb} KB)`);
